#!/usr/bin/env bash
# FDE Forge AI — one-command setup + start
#
# TCS Mac (no Docker): Homebrew Postgres/Redis/MinIO + native API/web, Bedrock on
# AWS EC2 (Docker):    docker compose up --build -d
#
# Usage (from repo root fde-forge-ai/):
#   chmod +x setup.sh
#   ./setup.sh
#
# Optional:
#   FORCE_MODE=native ./setup.sh     # force Homebrew path
#   FORCE_MODE=docker ./setup.sh     # force Docker path
#   WORKER_REPLICAS=4 ./setup.sh     # EC2 Celery scale (default 2)
#   SKIP_START=1 ./setup.sh          # install only
#   ./scripts/stop.sh                # stop native processes

set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
cd "$ROOT"

RUN_DIR="$ROOT/.run"
LOG_DIR="$RUN_DIR/logs"
PID_DIR="$RUN_DIR/pids"
NATIVE_ENV="$ROOT/.env.native"
COMPOSE_ENV="$ROOT/.env"

mkdir -p "$LOG_DIR" "$PID_DIR"

BLUE='\033[0;34m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
RED='\033[0;31m'
NC='\033[0m'

log()  { echo -e "${BLUE}==>${NC} $*"; }
ok()   { echo -e "${GREEN}✔${NC} $*"; }
warn() { echo -e "${YELLOW}!${NC} $*"; }
die()  { echo -e "${RED}✖${NC} $*"; exit 1; }

have() { command -v "$1" >/dev/null 2>&1; }

detect_mode() {
  if [[ "${FORCE_MODE:-}" == "native" || "${FORCE_MODE:-}" == "docker" ]]; then
    echo "$FORCE_MODE"
    return
  fi
  if have docker && docker info >/dev/null 2>&1 && docker compose version >/dev/null 2>&1; then
    echo "docker"
  else
    echo "native"
  fi
}

wait_http() {
  local url="$1" name="$2" tries="${3:-60}"
  local i=0
  while (( i < tries )); do
    if curl -sf "$url" >/dev/null 2>&1; then
      ok "$name is up ($url)"
      return 0
    fi
    sleep 1
    ((i++)) || true
  done
  warn "$name not responding yet at $url (check $LOG_DIR)"
  return 1
}

ensure_brew() {
  if have brew; then
    ok "Homebrew present"
    return
  fi
  die "Homebrew is required on TCS Mac (no Docker). Install from https://brew.sh then re-run ./setup.sh"
}

brew_install() {
  local pkg="$1"
  if brew list --versions "$pkg" >/dev/null 2>&1 || brew list --cask --versions "$pkg" >/dev/null 2>&1; then
    ok "$pkg already installed"
  else
    log "Installing $pkg..."
    brew install "$pkg"
  fi
}

write_native_env() {
  # Keep existing native .env so secret keys don't rotate on every re-run
  if [[ -f "$COMPOSE_ENV" ]] && grep -q '127.0.0.1:5432/fde_forge' "$COMPOSE_ENV" 2>/dev/null \
    && grep -q '^BEDROCK_ENABLED=true' "$COMPOSE_ENV" 2>/dev/null; then
    ok "Using existing .env (native + Bedrock)"
    return
  fi

  log "Writing native .env (localhost services + Bedrock only)..."
  local secret csrf existing_openai=""
