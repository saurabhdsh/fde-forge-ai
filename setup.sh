    secret="$(grep -E '^SECRET_KEY=' "$COMPOSE_ENV" 2>/dev/null | head -1 | cut -d= -f2- || true)"
    csrf="$(grep -E '^CSRF_SECRET=' "$COMPOSE_ENV" 2>/dev/null | head -1 | cut -d= -f2- || true)"
